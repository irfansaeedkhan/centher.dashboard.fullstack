const isEmpty = (value: any) => {
  return (
    value === undefined ||
    value === null ||
    (typeof value === "object" && Object.keys(value).length === 0) ||
    (typeof value === "string" && value.trim().length === 0)
  );
};

const delay = (ms: any) => new Promise((res) => setTimeout(res, ms));

export { isEmpty, delay };
